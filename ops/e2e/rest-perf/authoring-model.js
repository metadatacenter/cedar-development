// Builders for the authoring profile's template and its instances. They are pure, and import
// nothing from Node or k6, so setup and the load script build exactly the same documents.
//
// The minimal fixtures hold one unconstrained text field at most, so a write of one never reaches
// the checks a real template pays for: the regular expression and numeric bounds the validation
// library enforces on every instance, and the terminology lookup the artifact server makes for each
// distinct controlled-term value. This template has one field of each kind.

export const authoringOntology = {
  acronym: 'DOID',
  name: 'Human Disease Ontology',
  uri: 'https://data.bioontology.org/ontologies/DOID',
};

export const authoringFieldKeys = ['Title', 'Code', 'Count', 'Disease', 'Related'];

export function authoringPropertyIri(key) {
  return `https://schema.metadatacenter.org/properties/rest-perf-${key.toLowerCase()}`;
}

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function field(minimalField, key) {
  const body = clone(minimalField);
  body['@id'] = null;
  body['schema:name'] = key;
  body['schema:description'] = `${key} of the authoring fixture`;
  body.title = `${key} field schema`;
  body.description = `${key} field schema generated by the REST performance harness`;
  return body;
}

function controlledTermField(minimalField, key) {
  const body = field(minimalField, key);
  delete body.properties['@value'];
  body.properties['@id'] = { type: 'string', format: 'uri' };
  delete body.required;
  body._valueConstraints = {
    requiredValue: false,
    ontologies: [{ ...authoringOntology, numTerms: 0 }],
    valueSets: [],
    classes: [],
    branches: [],
    multipleChoice: false,
  };
  return body;
}

export function authoringTemplate(minimalTemplate, minimalField, name, description) {
  const template = clone(minimalTemplate);
  template['@id'] = null;
  template['schema:name'] = name;
  template['schema:description'] = description;

  const fields = {
    Title: field(minimalField, 'Title'),
    Code: field(minimalField, 'Code'),
    Count: field(minimalField, 'Count'),
    Disease: controlledTermField(minimalField, 'Disease'),
    Related: { type: 'array', minItems: 0, items: controlledTermField(minimalField, 'Related') },
  };
  fields.Code._valueConstraints = { requiredValue: false, regex: '^[A-Z]{2,5}-[0-9]{1,6}$' };
  fields.Count._ui.inputType = 'numeric';
  fields.Count._valueConstraints = {
    requiredValue: false, numberType: 'xsd:int', minValue: 0, maxValue: 100000,
  };
  fields.Count.required = ['@value', '@type'];

  for (const key of authoringFieldKeys) {
    template.properties[key] = fields[key];
    template.properties['@context'].properties[key] = { enum: [authoringPropertyIri(key)] };
    template.properties['@context'].required.push(key);
    template.required.push(key);
    template._ui.order.push(key);
    template._ui.propertyLabels[key] = key;
    template._ui.propertyDescriptions[key] = `${key} of the authoring fixture`;
  }
  return template;
}

/**
 * The values an instance carries. `terms` is the sample setup drew from the served index, each
 * `{ iri, label }`; `index` selects a reproducible window of it, so two writes of one instance
 * with different indexes present the server with different terms to verify.
 */
export function authoringValues(terms, index) {
  if (!Array.isArray(terms) || terms.length < 3) {
    throw new Error('the authoring profile needs at least three sampled terms');
  }
  const at = offset => terms[(((index + offset) % terms.length) + terms.length) % terms.length];
  const term = entry => ({ '@id': entry.iri, 'rdfs:label': entry.label });
  return {
    Title: { '@value': `Authoring record ${index}` },
    Code: { '@value': `PERF-${index % 1000000}` },
    Count: { '@value': String(index % 100000), '@type': 'xsd:int' },
    Disease: term(at(0)),
    Related: [term(at(1)), term(at(2))],
  };
}

export function authoringInstance(minimalInstance, templateId, name, description, values) {
  const instance = clone(minimalInstance);
  instance['@id'] = null;
  instance['schema:isBasedOn'] = templateId;
  instance['schema:name'] = name;
  instance['schema:description'] = description;
  instance['@context']['pav:derivedFrom'] = { '@type': '@id' };
  for (const key of authoringFieldKeys) {
    instance['@context'][key] = authoringPropertyIri(key);
    instance[key] = values[key];
  }
  return instance;
}

"""Plan optional root instance-annotation declarations; never rewrite existing declarations.

The caller supplies canonical JSON generated by the Java library and verified against TS.
Validate the complete candidate before writing. If relaxation_only is false, check live
dependent instances: an explicit declaration overrides an open additionalProperties schema.
"""
import copy

TEMPLATE = 'https://schema.metadatacenter.org/core/Template'
PATHS = ('/properties/_annotations', '/properties/@context/properties/_annotations')


def holder(schema, path):
    node = schema
    for part in path.split('/')[1:-1]:
        node = node[part]
        if not isinstance(node, dict):
            raise ValueError('non-object declaration container: ' + path)
    return node


def plan(source, canonical):
    if source.get('@type') != TEMPLATE:
        raise ValueError('only template root declarations are in scope')
    result = copy.deepcopy(source)
    changes = []
    relaxation_only = True
    for path in PATHS:
        old = holder(source, path)
        target = holder(canonical, path)['_annotations']
        if '_annotations' in old:
            if old['_annotations'] != target:
                raise ValueError('conflicting existing declaration: ' + path)
            continue
        container = source if path == PATHS[0] else source['properties']['@context']
        if '_annotations' in container.get('required', []):
            raise ValueError('annotation is already required: ' + path)
        # With no patternProperties and additionalProperties:false, any instance valid
        # before this addition could not contain the newly admitted property. Its verdict
        # cannot regress. Open containers need dependent-instance checks instead.
        relaxation_only &= (container.get('additionalProperties') is False
                            and not container.get('patternProperties'))
        holder(result, path)['_annotations'] = copy.deepcopy(target)
        changes.append(path)
    assert_additions(source, result, canonical, changes)
    return result, changes, relaxation_only


def assert_additions(source, candidate, canonical, changes):
    assert len(set(changes)) == len(changes) and set(changes) <= set(PATHS)
    restored = copy.deepcopy(candidate)
    for path in changes:
        assert '_annotations' not in holder(source, path)
        assert holder(restored, path).pop('_annotations') == holder(canonical, path)['_annotations']
    # Compare serialized pairs too: existing property order must survive this narrow edit.
    import json
    assert json.dumps(restored, ensure_ascii=False) == json.dumps(source, ensure_ascii=False), \
        'unexpected change outside the optional declarations'
